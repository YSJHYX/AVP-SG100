from pathlib import Path
import math

import mujoco
import numpy as np

from sg100_teleop.kinematics.rm65_ik import (
    RM65IKSolver,
    so3_log,
)


REPO_ROOT = Path(__file__).resolve().parents[2]

MODEL_PATH = (
    REPO_ROOT
    / "sg100_teleop"
    / "assets"
    / "rm65_sg100"
    / "mjcf"
    / "rm65_sg100_sim.xml"
)


def pose_error(
    solver,
    q,
    p_target,
    R_target,
):
    p, R = solver.fk(q)

    pos_error = float(
        np.linalg.norm(
            p_target - p
        )
    )

    rot_error = float(
        np.linalg.norm(
            so3_log(
                R_target @ R.T
            )
        )
    )

    return (
        pos_error,
        rot_error,
        p,
        R,
    )


def main():
    model = mujoco.MjModel.from_xml_path(
        str(MODEL_PATH)
    )

    solver = RM65IKSolver(
        model,
        tcp_body_name="sg100_base_link",
    )

    # Common IK seed.
    q_seed = np.array(
        [
             0.30,
            -0.40,
             0.35,
            -0.25,
             0.30,
             0.20,
        ],
        dtype=np.float64,
    )

    # Every target below is guaranteed reachable because
    # its Cartesian pose is generated by FK from a legal
    # RM65 joint configuration.
    q_targets = {
        "TARGET_A": np.array([
             0.35,
            -0.35,
             0.28,
            -0.20,
             0.34,
             0.24,
        ]),

        "TARGET_B": np.array([
             0.15,
            -0.50,
             0.45,
            -0.35,
             0.20,
             0.45,
        ]),

        "TARGET_C": np.array([
            -0.10,
            -0.30,
             0.25,
             0.20,
             0.40,
            -0.30,
        ]),

        "TARGET_D": np.array([
             0.45,
            -0.55,
             0.50,
            -0.10,
             0.25,
             0.70,
        ]),
    }

    failures = []

    print(
        "===== RM65 GUARANTEED-REACHABLE IK TEST ====="
    )

    print("\nseed q:")
    print(q_seed)

    for name, q_gt in q_targets.items():

        # -----------------------------------------------------
        # Generate a guaranteed-reachable Cartesian target.
        # -----------------------------------------------------
        p_target, R_target = solver.fk(
            q_gt
        )

        # -----------------------------------------------------
        # Solve from common seed.
        # -----------------------------------------------------
        q_solution, result = solver.solve(
            q_seed=q_seed,
            target_position=p_target,
            target_rotation=R_target,
        )

        (
            pos_error,
            rot_error,
            p_actual,
            R_actual,
        ) = pose_error(
            solver,
            q_solution,
            p_target,
            R_target,
        )

        print(
            "\n"
            + "=" * 72
        )
        print(name)
        print(
            "=" * 72
        )

        print("\nground-truth q:")
        print(q_gt)

        print("\nIK seed:")
        print(q_seed)

        print("\nIK solution:")
        print(q_solution)

        print(
            "\nq solution - q_gt:"
        )
        print(
            q_solution - q_gt
        )

        print(
            "\nconverged =",
            result.converged,
        )

        print(
            "iterations =",
            result.iterations,
        )

        print(
            "position error [mm] =",
            pos_error * 1000.0,
        )

        print(
            "rotation error [deg] =",
            math.degrees(
                rot_error
            ),
        )

        print(
            "sigma_min =",
            result.sigma_min,
        )

        print(
            "condition =",
            result.condition_number,
        )

        print(
            "damping =",
            result.damping,
        )

        within_limits = bool(
            np.all(
                q_solution
                >= solver.lower
            )
            and
            np.all(
                q_solution
                <= solver.upper
            )
        )

        print(
            "within joint limits =",
            within_limits,
        )

        passed = (
            result.converged
            and pos_error < 2e-4
            and rot_error < 2e-3
            and within_limits
        )

        print(
            "\nRESULT:",
            "PASS" if passed else "FAIL",
        )

        if not passed:
            failures.append(
                name
            )

    print(
        "\n"
        + "=" * 72
    )
    print("SUMMARY")
    print(
        "=" * 72
    )

    print(
        "failures =",
        failures,
    )

    if failures:
        raise RuntimeError(
            "Guaranteed-reachable IK failed: "
            + ", ".join(failures)
        )

    print(
        "\nGUARANTEED-REACHABLE IK: PASS"
    )


if __name__ == "__main__":
    main()
